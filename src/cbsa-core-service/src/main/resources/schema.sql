-- Canonical CBSA relational schema (shared contract; do not redefine elsewhere).
-- ACCOUNT, PROCTRAN and CONTROL use the legacy DB2 DDL column names verbatim
-- (etc/install/base/db2jcl/CRETB01-03.jcl, indexes CREI101-301).
-- CUSTOMER replaces the VSAM KSDS customer file (copybook CUSTOMER.cpy).
-- Portable between H2 (MODE=PostgreSQL) and PostgreSQL.

CREATE TABLE IF NOT EXISTS CUSTOMER (
    CUSTOMER_EYECATCHER        CHAR(4),
    CUSTOMER_SORTCODE          CHAR(6)      NOT NULL,
    CUSTOMER_NUMBER            CHAR(10)     NOT NULL,
    CUSTOMER_NAME              VARCHAR(60),
    CUSTOMER_ADDRESS           VARCHAR(160),
    CUSTOMER_DATE_OF_BIRTH     DATE,
    CUSTOMER_CREDIT_SCORE      INTEGER,
    CUSTOMER_CS_REVIEW_DATE    DATE,
    PRIMARY KEY (CUSTOMER_SORTCODE, CUSTOMER_NUMBER)
);

CREATE TABLE IF NOT EXISTS ACCOUNT (
    ACCOUNT_EYECATCHER         CHAR(4),
    ACCOUNT_CUSTOMER_NUMBER    CHAR(10),
    ACCOUNT_SORTCODE           CHAR(6)      NOT NULL,
    ACCOUNT_NUMBER             CHAR(8)      NOT NULL,
    ACCOUNT_TYPE               CHAR(8),
    ACCOUNT_INTEREST_RATE      DECIMAL(6, 2),
    ACCOUNT_OPENED             DATE,
    ACCOUNT_OVERDRAFT_LIMIT    INTEGER,
    ACCOUNT_LAST_STATEMENT     DATE,
    ACCOUNT_NEXT_STATEMENT     DATE,
    ACCOUNT_AVAILABLE_BALANCE  DECIMAL(12, 2),
    ACCOUNT_ACTUAL_BALANCE     DECIMAL(12, 2)
);
CREATE UNIQUE INDEX IF NOT EXISTS ACCTINDX ON ACCOUNT (ACCOUNT_SORTCODE, ACCOUNT_NUMBER);
CREATE INDEX IF NOT EXISTS ACCTCUST ON ACCOUNT (ACCOUNT_SORTCODE, ACCOUNT_CUSTOMER_NUMBER);

CREATE TABLE IF NOT EXISTS PROCTRAN (
    PROCTRAN_EYECATCHER        CHAR(4),
    PROCTRAN_SORTCODE          CHAR(6)      NOT NULL,
    PROCTRAN_NUMBER            CHAR(8)      NOT NULL,
    PROCTRAN_DATE              DATE,
    PROCTRAN_TIME              CHAR(6),
    PROCTRAN_REF               CHAR(12),
    PROCTRAN_TYPE              CHAR(3),
    PROCTRAN_DESC              CHAR(40),
    PROCTRAN_AMOUNT            DECIMAL(12, 2)
);
CREATE INDEX IF NOT EXISTS PROCINDX ON PROCTRAN (PROCTRAN_SORTCODE, PROCTRAN_NUMBER);

CREATE TABLE IF NOT EXISTS CONTROL (
    CONTROL_NAME               CHAR(32)     NOT NULL,
    CONTROL_VALUE_NUM          INTEGER,
    CONTROL_VALUE_STR          CHAR(40)
);
CREATE UNIQUE INDEX IF NOT EXISTS CONTINDX ON CONTROL (CONTROL_NAME);
