package com.ibm.cics.cip.bank.core.bankdata;

import com.ibm.cics.cip.bank.core.common.domain.Account;
import com.ibm.cics.cip.bank.core.common.domain.ControlRecord;
import com.ibm.cics.cip.bank.core.common.domain.Customer;
import com.ibm.cics.cip.bank.core.common.util.CbsaFormats;
import java.math.BigDecimal;
import java.math.RoundingMode;
import java.time.LocalDate;
import org.springframework.stereotype.Component;

/**
 * Renders a {@link GeneratedBank} as baseline/seed/seed.sql does ({@code legacy/tools/make_seed.py dump}):
 * header comment, then CUSTOMER, ACCOUNT, PROCTRAN (none from BANKDATA) and CONTROL INSERTs, each section
 * followed by a blank line; column names of schema.sql; CHAR keys zero-padded; DATE columns as ISO
 * {@code 'yyyy-MM-dd'} literals; decimals with two places; one statement per line.
 */
@Component
public class BankDataSqlWriter {

    static final String HEADER = """
            -- CBSA canonical seed data (sort code 987654).
            -- Generated by legacy/tools/make_seed.py from a run of the legacy
            -- BANKDATA program under the GnuCOBOL harness (see baseline/README.md).
            -- Do not edit by hand: regenerate with legacy/make-seed.sh.

            """;

    static final String CUSTOMER_COLUMNS = "CUSTOMER_EYECATCHER, CUSTOMER_SORTCODE, CUSTOMER_NUMBER, CUSTOMER_NAME, "
            + "CUSTOMER_ADDRESS, CUSTOMER_DATE_OF_BIRTH, CUSTOMER_CREDIT_SCORE, CUSTOMER_CS_REVIEW_DATE";

    static final String ACCOUNT_COLUMNS = "ACCOUNT_EYECATCHER, ACCOUNT_CUSTOMER_NUMBER, ACCOUNT_SORTCODE, "
            + "ACCOUNT_NUMBER, ACCOUNT_TYPE, ACCOUNT_INTEREST_RATE, ACCOUNT_OPENED, ACCOUNT_OVERDRAFT_LIMIT, "
            + "ACCOUNT_LAST_STATEMENT, ACCOUNT_NEXT_STATEMENT, ACCOUNT_AVAILABLE_BALANCE, ACCOUNT_ACTUAL_BALANCE";

    static final String CONTROL_COLUMNS = "CONTROL_NAME, CONTROL_VALUE_NUM, CONTROL_VALUE_STR";

    public String toSql(GeneratedBank bank) {
        StringBuilder sql = new StringBuilder(HEADER);
        for (Customer c : bank.customers()) {
            insert(sql, "CUSTOMER", CUSTOMER_COLUMNS, str(c.eyecatcher()), str(c.sortCode()),
                    str(CbsaFormats.customerNumber(c.customerNumber())), str(c.name()), str(c.address()),
                    date(c.dateOfBirth()), Integer.toString(c.creditScore()), date(c.creditScoreReviewDate()));
        }
        sql.append('\n');
        for (Account a : bank.accounts()) {
            insert(sql, "ACCOUNT", ACCOUNT_COLUMNS, str(a.eyecatcher()),
                    str(CbsaFormats.customerNumber(a.customerNumber())), str(a.sortCode()),
                    str(CbsaFormats.accountNumber(a.accountNumber())), str(a.accountType()),
                    decimal(a.interestRate()), date(a.opened()), Integer.toString(a.overdraftLimit()),
                    date(a.lastStatement()), date(a.nextStatement()), decimal(a.availableBalance()),
                    decimal(a.actualBalance()));
        }
        sql.append('\n');
        sql.append('\n'); // PROCTRAN section: BANKDATA writes no PROCTRAN rows
        for (ControlRecord r : bank.controls()) {
            insert(sql, "CONTROL", CONTROL_COLUMNS, str(r.name()),
                    r.valueNum() == null ? "NULL" : Long.toString(r.valueNum()), str(r.valueStr()));
        }
        return sql.toString();
    }

    private static void insert(StringBuilder sql, String table, String columns, String... values) {
        sql.append("INSERT INTO ").append(table).append(" (").append(columns).append(") VALUES (")
                .append(String.join(", ", values)).append(");\n");
    }

    private static String str(String value) {
        return value == null ? "NULL" : "'" + value.replace("'", "''") + "'";
    }

    private static String date(LocalDate value) {
        return value == null ? "NULL" : "'" + value + "'";
    }

    private static String decimal(BigDecimal value) {
        return value == null ? "NULL" : value.setScale(2, RoundingMode.HALF_EVEN).toPlainString();
    }
}
