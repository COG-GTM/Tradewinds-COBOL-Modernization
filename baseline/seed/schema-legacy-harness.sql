-- SQLite store used by the legacy GnuCOBOL harness (legacy/runtime/cbsastub.c).
-- Column names: ACCOUNT / PROCTRAN / CONTROL verbatim from the DB2 DDL in
-- etc/install/base/db2jcl/CRETB0*.jcl; CUSTOMER is the canonical relational
-- form of the VSAM CUSTOMER KSDS (key = sort code + customer number).
-- Dates are stored as ISO 'YYYY-MM-DD'; the runtime converts to/from the
-- DB2 'DD.MM.YYYY' host-variable format and the VSAM DDMMYYYY fields.
CREATE TABLE CUSTOMER (
  CUSTOMER_EYECATCHER      CHAR(4),
  CUSTOMER_SORTCODE        CHAR(6)  NOT NULL,
  CUSTOMER_NUMBER          CHAR(10) NOT NULL,
  CUSTOMER_NAME            VARCHAR(60),
  CUSTOMER_ADDRESS         VARCHAR(160),
  CUSTOMER_DATE_OF_BIRTH   DATE,
  CUSTOMER_CREDIT_SCORE    INTEGER,
  CUSTOMER_CS_REVIEW_DATE  DATE,
  PRIMARY KEY (CUSTOMER_SORTCODE, CUSTOMER_NUMBER)
);
CREATE TABLE ACCOUNT (
  ACCOUNT_EYECATCHER         CHAR(4),
  ACCOUNT_CUSTOMER_NUMBER    CHAR(10),
  ACCOUNT_SORTCODE           CHAR(6) NOT NULL,
  ACCOUNT_NUMBER             CHAR(8) NOT NULL,
  ACCOUNT_TYPE               CHAR(8),
  ACCOUNT_INTEREST_RATE      DECIMAL(6, 2),
  ACCOUNT_OPENED             DATE,
  ACCOUNT_OVERDRAFT_LIMIT    INTEGER,
  ACCOUNT_LAST_STATEMENT     DATE,
  ACCOUNT_NEXT_STATEMENT     DATE,
  ACCOUNT_AVAILABLE_BALANCE  DECIMAL(12, 2),
  ACCOUNT_ACTUAL_BALANCE     DECIMAL(12, 2),
  PRIMARY KEY (ACCOUNT_SORTCODE, ACCOUNT_NUMBER)
);
CREATE TABLE PROCTRAN (
  PROCTRAN_EYECATCHER  CHAR(4),
  PROCTRAN_SORTCODE    CHAR(6) NOT NULL,
  PROCTRAN_NUMBER      CHAR(8) NOT NULL,
  PROCTRAN_DATE        DATE,
  PROCTRAN_TIME        CHAR(6),
  PROCTRAN_REF         CHAR(12),
  PROCTRAN_TYPE        CHAR(3),
  PROCTRAN_DESC        CHAR(40),
  PROCTRAN_AMOUNT      DECIMAL(12, 2)
);
CREATE TABLE CONTROL (
  CONTROL_NAME       CHAR(32) NOT NULL PRIMARY KEY,
  CONTROL_VALUE_NUM  INTEGER,
  CONTROL_VALUE_STR  CHAR(40)
);
