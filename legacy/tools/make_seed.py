#!/usr/bin/env python3
"""Build baseline/seed/seed.sql from a harness database after BANKDATA has
populated it (usage: make_seed.py load-customers <db> <custfile> | dump <db> <out>) (CUSTOMER records come from the sequential CUSTOMER file BANKDATA
writes; ACCOUNT/CONTROL/PROCTRAN from the SQLite store)."""
import sqlite3
import sys

CUST_LEN = 259


def q(v):
    if v is None:
        return 'NULL'
    if isinstance(v, (int, float)):
        return repr(v) if isinstance(v, int) else ('%.2f' % v)
    return "'" + str(v).replace("'", "''") + "'"


def iso(ddmmyyyy):
    return '%s-%s-%s' % (ddmmyyyy[4:8], ddmmyyyy[2:4], ddmmyyyy[0:2])


def customers(path):
    data = open(path, 'rb').read().decode('latin-1')
    for i in range(0, len(data) - CUST_LEN + 1, CUST_LEN):
        r = data[i:i + CUST_LEN]
        if r[0:4] != 'CUST':
            continue  # BANKDATA also writes the CTRL record (kept in CONTROL)
        yield (r[0:4], r[4:10], r[10:20], r[20:80].rstrip(), r[80:240].rstrip(),
               iso(r[240:248]), int(r[248:251]), iso(r[251:259]))


def load_customers(dbpath, custfile):
    """Insert BANKDATA's CUSTOMER file records (and CTRL counters) into the store."""
    db = sqlite3.connect(dbpath)
    n = 0
    for c in customers(custfile):
        db.execute('INSERT INTO CUSTOMER VALUES (?,?,?,?,?,?,?,?)', c)
        n += 1
    data = open(custfile, 'rb').read().decode('latin-1')
    for i in range(0, len(data) - CUST_LEN + 1, CUST_LEN):
        r = data[i:i + CUST_LEN]
        if r[0:4] == 'CTRL':
            for name, val in (('987654-CUSTOMER-COUNT', int(r[20:30])), ('987654-CUSTOMER-LAST', int(r[30:40]))):
                db.execute("INSERT OR REPLACE INTO CONTROL VALUES (?, ?, '')", (name, val))
    db.commit()
    print('customers=%d' % n)


def dump(dbpath, out):
    db = sqlite3.connect(dbpath)
    lines = ['-- CBSA canonical seed data (sort code 987654).',
             '-- Generated by legacy/tools/make_seed.py from a run of the legacy',
             '-- BANKDATA program under the GnuCOBOL harness (see baseline/README.md).',
             '-- Do not edit by hand: regenerate with legacy/make-seed.sh.', '']
    cols = ('CUSTOMER_EYECATCHER, CUSTOMER_SORTCODE, CUSTOMER_NUMBER, CUSTOMER_NAME, CUSTOMER_ADDRESS, '
            'CUSTOMER_DATE_OF_BIRTH, CUSTOMER_CREDIT_SCORE, CUSTOMER_CS_REVIEW_DATE')
    cur = db.execute('SELECT * FROM CUSTOMER ORDER BY CUSTOMER_SORTCODE, CUSTOMER_NUMBER')
    for c in cur:
        lines.append('INSERT INTO CUSTOMER (%s) VALUES (%s);' % (cols, ', '.join(q(x) for x in c)))
    lines.append('')
    for table, order in (('ACCOUNT', 'ACCOUNT_SORTCODE, ACCOUNT_NUMBER'),
                         ('PROCTRAN', 'rowid'), ('CONTROL', 'CONTROL_NAME')):
        cur = db.execute('SELECT * FROM %s ORDER BY %s' % (table, order))
        names = [d[0] for d in cur.description]
        for row in cur:
            vals = []
            for n, v in zip(names, row):
                if v is not None and n.endswith(('_OPENED', '_STATEMENT', '_DATE')) and isinstance(v, str) and len(v) == 10:
                    vals.append(q(v))
                elif v is not None and n.endswith(('_RATE', '_BALANCE', '_AMOUNT')):
                    vals.append('%.2f' % float(v))
                else:
                    vals.append(q(v))
            lines.append('INSERT INTO %s (%s) VALUES (%s);' % (table, ', '.join(names), ', '.join(vals)))
        lines.append('')
    open(out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    if sys.argv[1] == 'load-customers':
        load_customers(sys.argv[2], sys.argv[3])
    else:
        dump(sys.argv[2], sys.argv[3])
